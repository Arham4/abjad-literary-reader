/**
 * Resolves vocalized form with harakat for any Urdu word.
 */
export function vocalizeUrduWord(word: string): string {
  if (!word) return '';
  const trimmed = word.trim();
  const clean = trimmed.replace(/^[،۔؛:؟!«»"'“”‘’()[\]{}—–.,?!-]+|[،۔؛:؟!«»"'“”‘’()[\]{}—–.,?!-]+$/gu, '').trim();

  if (URDU_VOCALIZATION_MAP[clean]) {
    return URDU_VOCALIZATION_MAP[clean];
  }
  if (URDU_VOCALIZATION_MAP[trimmed]) {
    return URDU_VOCALIZATION_MAP[trimmed];
  }

  // If already vocalized with diacritics, preserve it
  if (/[\u064B-\u0652\u0670\u0653]/.test(trimmed)) {
    return trimmed;
  }

  // Intelligent fallback harakat assignment: ensures every Urdu word has vowel diacritics
  if (clean.length >= 1) {
    const chars = Array.from(clean);
    const first = chars[0];
    const second = chars[1];
    if (first !== 'آ' && first !== 'ں') {
      let diacritic = '\u064E'; // Default Zabar (َ)
      if (second === 'و') {
        diacritic = '\u064F'; // Pesh (ُ) before Waw
      } else if (second === 'ی' || second === 'ے') {
        diacritic = '\u0650'; // Zer (ِ) before Yeh
      } else if (first === 'ا' && clean.length > 1) {
        diacritic = '\u0650'; // Zer (ِ) on initial Alif for grammatical words like اس، ان
      }
      return `${first}${diacritic}${chars.slice(1).join('')}`;
    }
  }

  return clean;
}

/**
 * Enhanced decomposition of vocalized Urdu text into individual phonetic pills
 * with proper grouping of aspirated digraphs (بھ، پھ، تھ، گھ...) and
 * exact vowel/diacritic labels (زبر، زیر، پیش، جزم، تشدید...).
 */
export function makePhoneticBreakdown(vocalized: string): PhoneticSyllablePill[] {
  const pills: PhoneticSyllablePill[] = [];
  const chars = Array.from(vocalized);
  let i = 0;

  while (i < chars.length) {
    let base = chars[i];
    i++;

    // Check for 2-character aspirated digraph (consonant + Doachashmee Heh \u06BE)
    if (i < chars.length && chars[i] === '\u06BE') {
      base += chars[i];
      i++;
    }

    // Collect all diacritics attached to this base
    let diacritics = '';
    while (i < chars.length && /[\u064B-\u0652\u0670\u0653]/.test(chars[i])) {
      diacritics += chars[i];
      i++;
    }

    // Determine the precise vowel/diacritic name
    let vName: string | undefined = undefined;
    if (diacritics.includes('\u0651')) {
      if (diacritics.includes('\u064E')) vName = 'تشدید و زبر';
      else if (diacritics.includes('\u0650')) vName = 'تشدید و زیر';
      else if (diacritics.includes('\u064F')) vName = 'تشدید و پیش';
      else vName = 'تشدید';
    } else if (diacritics.includes('\u0653')) {
      vName = 'مد';
    } else if (diacritics.includes('\u0670')) {
      vName = 'کھڑی زبر';
    } else if (diacritics.includes('\u064B')) {
      vName = 'دو زبر (تنوین)';
    } else if (diacritics.includes('\u064E')) {
      vName = 'زبر';
    } else if (diacritics.includes('\u0650')) {
      vName = 'زیر';
    } else if (diacritics.includes('\u064F')) {
      vName = 'پیش';
    } else if (diacritics.includes('\u0652')) {
      vName = 'جزم';
    } else if (base === 'آ') {
      vName = 'الف مدہ';
    } else if (base === 'ں') {
      vName = 'نون غنہ';
    } else if (base === 'ا') {
      vName = 'الف';
    } else if (base === 'و') {
      vName = 'واؤ';
    } else if (base === 'ی') {
      vName = 'چھوٹی یے';
    } else if (base === 'ے') {
      vName = 'بڑی یے';
    } else if (base.trim()) {
      vName = 'ساکن';
    }

    if (base.trim()) {
      pills.push({
        letters: base + diacritics,
        vowelNameUrdu: vName,
      });
    }
  }

  return pills;
}
